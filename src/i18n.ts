// - 문구를 고치려면 아래 ko / en / ja 객체에서 같은 키의 값을 수정하세요.
// - 새 문구를 추가할 때는 ko에 먼저 키를 만들면 en / ja에도 같은 키가 없을 때 빌드가 막혀서 빠뜨리지 않습니다.
// - {name}, {n} 같은 자리표시자는 translate()가 값으로 바꿔 줍니다.

export type Lang = "ko" | "en" | "ja";

export const LANGS: Lang[] = ["ko", "en", "ja"];
