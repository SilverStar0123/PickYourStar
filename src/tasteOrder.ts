const characterRank = new Map(TASTE_CHARACTER_ORDER.map((id, index) => [id, index]));
export function orderedTasteCatalog<T extends Character>(catalog: readonly T[]): T[] {
  const key = (c: T) => `${c.unit}::${c.name}`;
  return catalog.filter(c => characterRank.has(key(c)))
    .sort((a, b) => characterRank.get(key(a))! - characterRank.get(key(b))!);
}
